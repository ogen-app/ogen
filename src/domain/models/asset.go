package models

import (
	"time"

	"github.com/uptrace/bun"
)

const (
	AssetStatusPending    = "pending"
	AssetStatusProcessing = "processing"
	AssetStatusReady      = "ready"
	AssetStatusPartial    = "partial"
	AssetStatusFailed     = "failed"
)

const (
	// AssetTypeMarkdown marks assets imported from a `.md` upload.
	AssetTypeMarkdown = "MD"
	// AssetTypePDF marks assets imported from a `.pdf` upload.
	AssetTypePDF = "PDF"
	// AssetTypeURL marks assets scraped from a web page URL.
	AssetTypeURL = "URL"
	// AssetTypeImage marks assets that are an uploaded image. Its
	// content is a plain-text description, not a document; empty is valid.
	AssetTypeImage = "IMG"
	// AssetTypeDocument marks assets imported from an office/text document upload
	// parsed by document-service: .docx/.pptx/.xlsx/.odt/.ods/.odp/
	// .epub/.csv/.tsv/.html/.xhtml/.eml/.rtf/.txt/.log. The specific format is
	// recorded in asset_files.mime_type; assets.type stays a coarse enum.
	AssetTypeDocument = "DOC"
	// AssetTypeAudio marks assets imported from an audio upload transcribed by
	// audio-service: mp3/wav/aac-m4a/ogg-opus/flac/webm/aiff. The
	// specific format is recorded in asset_files.mime_type; the searchable
	// content is the assembled transcript, chunked with time-range anchors.
	AssetTypeAudio = "AUDIO"
)

// AssetCodeContentLocked is the machine-readable code on the 409 a PUT gets when
// it tries to change the content of a service-ingested PDF/DOC/AUDIO asset:
// that content is the ingestion service's output, so an edit is
// refused. The client should re-extract instead.
const AssetCodeContentLocked = "content_locked"

// IsServiceIngestedAssetType reports whether an asset's chunks come from an
// ingestion service (PDF/DOC/AUDIO/IMG) rather than the markdown embed of its
// title + content. Those chunks carry source_label/source_anchor and
// don't depend on the title, so a rename must never re-chunk them.
func IsServiceIngestedAssetType(t *string) bool {
	if t == nil {
		return false
	}
	switch *t {
	case AssetTypePDF, AssetTypeDocument, AssetTypeAudio, AssetTypeImage:
		return true
	}
	return false
}

// AssetOriginFigma marks an asset a Figma plugin sent.
const AssetOriginFigma = "figma"

// AssetOriginRef points an asset back at its source. For Figma: the node
// (frame) id and name, the document name and, only from private org builds
// that can read it, the file key.
type AssetOriginRef struct {
	NodeID   string `json:"node_id"`
	NodeName string `json:"node_name"`
	FileName string `json:"file_name,omitempty"`
	FileKey  string `json:"file_key,omitempty"`
}

type Asset struct {
	bun.BaseModel `bun:"table:assets,alias:a" swaggerignore:"true"`
	TenantScoped  // tenant_id column + central scoping hooks

	ID      string  `bun:"id,pk"                                        json:"id"`
	Title   string  `bun:"title,notnull"                                json:"title"`
	Content string  `bun:"content,notnull"                              json:"content"`
	Status  string  `bun:"status,notnull,default:'ready'"               json:"status"`
	Type    *string `bun:"type"                                         json:"type"`
	// SourceURL is the origin URL for URL-scraped assets; nil for
	// MD/PDF/text assets. Unique per tenant, so re-submitting a URL refreshes
	// the same asset instead of duplicating it.
	SourceURL *string `bun:"source_url"                                   json:"source_url,omitempty"`
	// AltText is a short accessibility description for image assets,
	// distinct from content (the longer, embeddable description). Empty for
	// non-image assets. For images it is auto-generated by image-service unless a
	// user has edited it (CON-281, see AltTextEditedByUser).
	AltText string `bun:"alt_text,notnull,default:''"                  json:"alt_text"`
	// AltTextEditedByUser guards a user's manual alt text from being overwritten
	// by (re-)processing: image-service fills AltText only while this
	// is false; a PUT that sets alt_text flips it true, so re-extraction never
	// clobbers a human edit.
	AltTextEditedByUser bool `bun:"alt_text_edited_by_user,notnull,default:false" json:"alt_text_edited_by_user"`
	// FailureCode/FailureReason say why ingestion failed: a stable
	// models.UploadCode* plus tenant-visible prose. Set only while status is
	// failed; any other status write clears them. Written for DOC assets —
	// audio/image carry theirs on the extraction row.
	FailureCode   string `bun:"failure_code,notnull,default:''"              json:"failure_code,omitempty"`
	FailureReason string `bun:"failure_reason,notnull,default:''"            json:"failure_reason,omitempty"`
	// Origin is where the asset came from beyond a plain upload ('' for
	// uploads, AssetOriginFigma for frames a Figma plugin sent); OriginRef is
	// the origin-specific pointer back to the source. A checksum-dedupe hit
	// keeps the first asset's provenance.
	Origin    string          `bun:"origin,notnull,default:''"                    json:"origin"`
	OriginRef *AssetOriginRef `bun:"origin_ref,type:jsonb"                        json:"origin_ref,omitempty"`
	TagIDs    StringSlice     `bun:"tag_ids,notnull,type:jsonb"                   json:"tag_ids"`
	Tags      []Tag           `bun:"-"                                            json:"tags"`
	File      *AssetFile      `bun:"-"                                            json:"file,omitempty"`
	// Images are the mirrored page images for URL assets, hydrated and
	// URL-decorated by the handler layer. Not persisted on assets.
	Images    []AssetImage `bun:"-" json:"images,omitempty"`
	CreatedBy string       `bun:"created_by,notnull"                           json:"created_by"`
	CreatedAt time.Time    `bun:"created_at,notnull,default:current_timestamp" json:"created_at"`
	UpdatedAt time.Time    `bun:"updated_at,notnull,default:current_timestamp" json:"updated_at"`
}
